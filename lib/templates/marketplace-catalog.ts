import type { AllowedAgentTool } from "@/lib/xai/parse-agent-build";
import { mapTriggerToRuntime, safetyDefaultsForRisk } from "./safety-defaults";
import type {
  AgentTemplate,
  MarketplaceCategory,
  TemplateRiskLevel,
  TemplateTrigger,
} from "./types";

interface CatalogDraft {
  slug: string;
  name: string;
  shortDescription: string;
  longDescription: string;
  category: MarketplaceCategory;
  icon: string;
  tags: string[];
  riskLevel: TemplateRiskLevel;
  estimatedSetupMinutes: number;
  suggestedIntegrations: string[];
  tools: AllowedAgentTool[];
  defaultInstructions: string;
  exampleTasks: string[];
  defaultTrigger: TemplateTrigger;
  supportsThreshold?: boolean;
  defaultThreshold?: number | null;
  isFeatured?: boolean;
  sortOrder: number;
}

function hydrate(draft: CatalogDraft): AgentTemplate {
  const safety = safetyDefaultsForRisk(draft.riskLevel, draft.tools);
  const triggerType = mapTriggerToRuntime(draft.defaultTrigger);
  return {
    id: draft.slug,
    slug: draft.slug,
    name: draft.name,
    description: draft.shortDescription,
    summary: draft.shortDescription,
    shortDescription: draft.shortDescription,
    longDescription: draft.longDescription,
    icon: draft.icon,
    category: draft.category,
    defaultDescription: draft.longDescription,
    tools: draft.tools,
    triggerType,
    defaultTrigger: draft.defaultTrigger,
    supportsThreshold: draft.supportsThreshold ?? draft.riskLevel !== "low",
    defaultThreshold: draft.defaultThreshold ?? (draft.riskLevel === "low" ? null : 5000),
    tags: draft.tags,
    riskLevel: draft.riskLevel,
    estimatedSetupMinutes: draft.estimatedSetupMinutes,
    suggestedIntegrations: draft.suggestedIntegrations,
    defaultInstructions: draft.defaultInstructions,
    exampleTasks: draft.exampleTasks,
    defaultSafetyPreset: safety.preset,
    defaultToolPermissions: safety.toolPermissions,
    defaultApprovalRules: safety.approvalRules,
    defaultExecutionLimits: safety.executionLimits,
    defaultDataProtection: safety.dataProtection,
    requiresApproval: safety.requiresApproval,
    isFeatured: draft.isFeatured ?? false,
    isPublished: true,
    sortOrder: draft.sortOrder,
  };
}

